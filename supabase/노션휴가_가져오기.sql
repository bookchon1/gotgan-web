insert into public.leave_records
  (employee_id, leave_type, status, start_date, end_date, days, reason, approved_at)
select e.id, s.ltype, s.st, s.sdate::date, s.edate::date, s.d, s.reason,
       case when s.st = '승인' then now() else null end
from src s
join public.employees e on e.name = s.nm
where not exists (
  select 1 from public.leave_records lr
  where lr.employee_id = e.id
    and lr.start_date = s.sdate::date
    and lr.leave_type = s.ltype
);

-- 확인: 사람별 승인 휴가 일수/건수
